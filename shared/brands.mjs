export const BRANDS = {
  hama: { id: 'hama', label: 'Hama', colors: HAMA_COLORS, prefix: 'H' },
  perler: { id: 'perler', label: 'Perler', colors: PERLER_COLORS, prefix: 'P' },
  artkal: { id: 'artkal', label: 'Artkal S', colors: ARTKAL_COLORS, prefix: 'S' },
};

function rgb(hex) {
  const n = parseInt(hex.replace('#', ''), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

function dist(a, b) {
  const rm = (a.r + b.r) / 2;
  const dr = a.r - b.r;
  const dg = a.g - b.g;
  const db = a.b - b.b;
  return (2 + rm / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rm) / 256) * db * db;
}

/** 返回所选品牌里最接近的色号。 */
export function nearestBrand(hex, brand = 'hama') {
  const set = BRANDS[brand] || BRANDS.hama;
  const c = rgb(hex);
  let best = set.colors[0];
  let bestD = Infinity;
  for (const h of set.colors) {
    const d = dist(c, rgb(h.hex));
    if (d < bestD) {
      bestD = d;
      best = h;
    }
  }
  return { ...best, brand: set.id, delta: Math.round(Math.sqrt(bestD)) };
}

export function nearestHama(hex) {
  return nearestBrand(hex, 'hama');
}
